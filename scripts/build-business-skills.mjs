import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const ids=['corporate-strategy','operations-management','sales-marketing','people-management','research-development','financial-management','business-systemization'];
export async function buildSkillResources(root){const resources={};
for(const id of ids){
 const source='business-hq/skills/'+id+'/SKILL.md';
 const content=await readFile(path.join(root,source),'utf8');
 const version=content.match(/版本：(\d+\.\d+\.\d+)/)?.[1];
 if(!version||!content.includes('name: '+id)||!content.includes('approval_required'))throw Error('Invalid skill: '+id);
 resources[id]={id,version,hash:createHash('sha256').update(content).digest('hex'),source,content};
}
return resources;}
if(process.argv[1]===fileURLToPath(import.meta.url)){
const resources=await buildSkillResources(root);
const out='// Generated by scripts/build-business-skills.mjs; edit the source SKILL.md instead.\nexport const skillResources='+JSON.stringify(resources,null,2)+';\n';
const target=path.join(root,'supabase/functions/hana-automation/hq-skills.generated.mjs');
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==out)throw Error('Skill bundle is stale; run node scripts/build-business-skills.mjs');
 console.log('PASS: seven executable skill resources match their Markdown versions and SHA-256.');
}else await writeFile(target,out);
}
