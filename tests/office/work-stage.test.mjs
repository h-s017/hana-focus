import assert from 'node:assert/strict';
import {workStage,workStageText,workStages} from '../../js/work-stage.mjs';
const task=(id,patch={})=>({id,status:'queued',scope_status:'in_scope',work_state:'todo',task_kind:'agent',is_current:true,...patch});
const queued=task('queued'),running=task('running',{status:'running'}),review=task('review',{status:'review'});
assert.equal(workStage(queued),'assigned');
assert.equal(workStage(running),'working');
assert.equal(workStage(review),'decision');
assert.equal(workStage(task('approved',{status:'approved'})),'assigned','approved draft must not imply completed work');
assert.match(workStageText(task('approved',{status:'approved'})),/仍待執行/);
assert.equal(workStage(task('manual',{task_kind:'tracking',work_state:'in_progress'})),'working');
assert.equal(workStageText(task('manual',{work_state:'in_progress'})),'工作已標記進行中','manual progress must not claim tool execution');
for(const status of ['failed','rejected'])assert.equal(workStage(task(status,{status})),'decision');
assert.equal(workStage(task('scope',{scope_status:'needs_review'})),'decision');
assert.equal(workStage(task('waiting',{work_state:'waiting'})),'decision');
const dependent=task('dependent',{dependencies:['previous']}),previous=task('previous',{work_state:'done'});
assert.equal(workStage(dependent),'decision','missing dependencies require attention');
assert.equal(workStage(dependent,[previous]),'assigned');
assert.equal(workStage(dependent,[{...previous,scope_status:'out_of_scope'}]),'decision');
const archived=[task('outside',{scope_status:'out_of_scope'}),task('old',{is_current:false}),previous];
for(const item of archived)assert.equal(workStage(item),'archived');
assert.match(workStageText(archived[0]),/不屬於本次範圍/);
assert.match(workStageText(previous),/尚不代表客戶核准/);
const groups=workStages([queued,running,review,...archived]);
assert.deepEqual(Object.fromEntries(Object.entries(groups).map(([key,list])=>[key,list.map(t=>t.id)])),{assigned:['queued'],working:['running'],decision:['review']});
assert.deepEqual(workStages([task('later',{priority:3}),task('urgent',{priority:1}),task('first',{priority:1,due_at:'2026-10-27'})]).assigned.map(t=>t.id),['first','urgent','later']);
assert.deepEqual(workStages([]),{assigned:[],working:[],decision:[]});
console.log('PASS: queued work, actual tool execution, manual progress, draft review, dependencies and archived scope remain distinct.');
