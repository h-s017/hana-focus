import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const read=name=>readFileSync(fileURLToPath(new URL('../../'+name,import.meta.url)),'utf8');
const html=read('canva-oauth-callback.html');
const code=read('js/canva-oauth-callback.mjs');
const builder=read('scripts/build-office-site.mjs');
const url='https://h-s017.github.io/hana-focus/canva-oauth-callback.html';
assert.equal(new URL(url).origin,'https://h-s017.github.io');
assert.ok(builder.includes("'canva-oauth-callback.html'"));
assert.ok(html.includes('<meta name="referrer" content="no-referrer">'));
assert.ok(html.includes('noindex,nofollow,noarchive'));
assert.ok(html.includes('./js/canva-oauth-callback.mjs'));
assert.ok(code.indexOf("history.replaceState")>0);
assert.ok(!code.includes('fetch('));
assert.ok(!code.includes('sendBeacon('));
assert.ok(!code.includes('localStorage'));
assert.ok(code.includes('sessionStorage'));
assert.ok(code.includes('finishCanvaConnection'));
assert.ok(code.indexOf('history.replaceState')<code.indexOf("import('./office-client.mjs')"));
console.log('PASS: Canva OAuth callback exists in staged site and never sends authorization code without a configured secure backend.');
