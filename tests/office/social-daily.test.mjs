import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {lessonForDay,microLessons} from '../../social-editor/editorial-library.mjs';
import {dailyVisuals,dailyVisualBrief} from '../../social-editor/visual-preset.mjs';
const script=fileURLToPath(new URL('../../scripts/social-editor.mjs',import.meta.url));
const dir=mkdtempSync(path.join(tmpdir(),'hana-social-fixture-'));
const run=date=>{
 const r=spawnSync(process.execPath,[script],{cwd:dir,env:{...process.env,LESSON_DATE:date},encoding:'utf8'});
 assert.equal(r.status,0,r.stderr||r.stdout);
 return JSON.parse(readFileSync(path.join(dir,'content/instagram/latest.json'),'utf8'));
};
assert.equal(microLessons.length,44);
assert.equal(new Set(microLessons.map(x=>x.title)).size,44);
for(const x of microLessons)assert.equal(x.pages.length,6);
assert.equal(lessonForDay(8).pages.length,6);
assert.equal(lessonForDay(15).pages.length,6);
assert.equal(lessonForDay(44).pages.length,6);
assert.equal(lessonForDay(45),null);
assert.throws(()=>dailyVisuals({style:''}),/daily_visual_style_required/);
assert.equal(dailyVisuals(lessonForDay(9)).style,'古典音樂手稿');
assert.notEqual(dailyVisuals(lessonForDay(9)).style,dailyVisuals(lessonForDay(10)).style);
assert.match(dailyVisualBrief(lessonForDay(9)),/保留原 Canva 的可編輯字體、字級、文字位置/);
const first=run('2026-10-26');
assert.equal(first.day,8);
assert.equal(first.status,'editorial_ready');
assert.equal(first.canvaCreated,false);
assert.equal(first.slideCount,0);
assert.equal(first.plannedSlideCount,6);
assert.equal(first.published,false);
assert.ok(first.canvaCsvPath.endsWith('2026-10-26/canva-autofill.csv'));
const lesson=JSON.parse(readFileSync(path.join(dir,'content/instagram/2026-10-26/lesson.json'),'utf8'));
assert.deepEqual(lesson.canvas,{width:1080,height:1350,pages:6});
assert.equal(lesson.pages.length,6);
assert.equal(lesson.visuals.style,'柔和藝術攝影');
assert.equal(lesson.visuals.layout_reference_design_id,'DAHYaeidsPw');
assert.equal(lesson.visuals.layout_status,'not_verified');
assert.equal(lesson.visuals.preset_id,'hana-art-editorial-2026-10-20');
const brief=readFileSync(path.join(dir,'content/instagram/2026-10-26/visual-brief.md'),'utf8');
assert.ok(brief.includes('DAHYaeidsPw')&&brief.includes('不固定紙白水彩或全黑背景'));
assert.equal(lesson.music.recordingRights.includes('未取得'),true);
const html=readFileSync(path.join(dir,'content/instagram/2026-10-26/canva-import.html'),'utf8');
assert.equal((html.match(/data-document-role="page"/g)||[]).length,6);
assert.equal((html.match(/width:1080px;height:1350px/g)||[]).length,6);
assert.ok(html.includes('前景與背景：氣味設計的層次'));
assert.ok(html.includes('描述一個空間：主角是一種材質，背景是一種氣氛。'));
assert.ok(!html.includes('<script'));
assert.equal(first.canvaImportPath,'content/instagram/2026-10-26/canva-import.html');
const csv=readFileSync(path.join(dir,'content/instagram/2026-10-26/canva-autofill.csv'),'utf8');
assert.equal(csv.charCodeAt(0),0xFEFF);
assert.ok(csv.includes('PAGE_01_TITLE')&&csv.includes('PAGE_06_BODY'));
assert.ok(csv.includes('前景與背景'));
const caption=readFileSync(path.join(dir,'content/instagram/2026-10-26/caption.md'),'utf8');
assert.ok(caption.includes('HANA 嗅覺微課｜Day 008')&&caption.includes('音樂聆賞'));
assert.ok(!caption.includes('已發布 Instagram'));
const previous={...first,canvaCreated:true,canvaDesignId:'TEST_CANVA_DESIGN',canvaEditUrl:'https://www.canva.com/design/TEST_CANVA_DESIGN/edit',slideCount:6};
writeFileSync(path.join(dir,'content/instagram/latest.json'),JSON.stringify(previous));
const rerun=run('2026-10-26');
assert.equal(rerun.canvaCreated,true);
assert.equal(rerun.canvaDesignId,'TEST_CANVA_DESIGN');
assert.equal(rerun.published,false);
const november=run('2026-11-02');
assert.equal(november.day,15);
assert.equal(november.status,'editorial_ready');
assert.equal(november.plannedSlideCount,6);
assert.equal(november.published,false);
const final=run('2026-12-02');
assert.equal(final.day,45);
assert.equal(final.status,'needs-lesson');
assert.equal(final.canvaCreated,false);
assert.equal(final.topic,null);
const bad=spawnSync(process.execPath,[script],{cwd:dir,env:{...process.env,LESSON_DATE:'2026-02-30'},encoding:'utf8'});
assert.notEqual(bad.status,0);
console.log('PASS: 44 curated lessons, 6-page daily Canva CSV/caption package, no false delivery, idempotent same-day state, missing-lesson fail-closed.');
